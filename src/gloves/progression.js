import {
  GLOVES,
  GLOVE_ROSTER,
  DEFAULT_GLOVE,
  canUseGlove,
  sanitizeSlaps,
} from "./catalog.js";
const KEY = "slap-arena-profile-v1";
export function sanitizeProfile(value) {
  const slaps = sanitizeSlaps(value?.slaps);
  return {
    version: 1,
    slaps,
    selected: canUseGlove(value?.selected, slaps)
      ? value.selected
      : DEFAULT_GLOVE,
  };
}
export function readProfile(storage) {
  try {
    return sanitizeProfile(
      JSON.parse((storage ?? globalThis.localStorage)?.getItem(KEY) || "{}"),
    );
  } catch {
    return sanitizeProfile(null);
  }
}
export function writeProfile(profile, storage) {
  const safe = sanitizeProfile(profile);
  try {
    (storage ?? globalThis.localStorage)?.setItem(KEY, JSON.stringify(safe));
  } catch {
    /* Private browsing: session progress still works. */
  }
  return safe;
}
export class SlapProgression {
  constructor(storage) {
    this.storage = storage;
    this.profile = readProfile(storage);
    this.listeners = new Set();
    this.seen = new Set();
  }
  subscribe = (listener) => {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  };
  getSnapshot = () => this.profile;
  update(next) {
    this.profile = writeProfile(next, this.storage);
    for (const f of this.listeners) f();
    return this.profile;
  }
  select(id) {
    if (!canUseGlove(id, this.profile.slaps)) return false;
    this.update({ ...this.profile, selected: id });
    return true;
  }
  // Receipts are authority-issued (or offline simulation-issued), never generated by a swing animation.
  award(receipt) {
    if (typeof receipt !== "string" || !receipt || this.seen.has(receipt))
      return false;
    this.seen.add(receipt);
    if (this.seen.size > 2048)
      this.seen.delete(this.seen.values().next().value);
    this.update({
      ...this.profile,
      slaps: Math.min(10_000_000, this.profile.slaps + 1),
    });
    return true;
  }
  next() {
    return GLOVE_ROSTER.find((g) => g.cost > this.profile.slaps) || null;
  }
}
export const progression = new SlapProgression();
