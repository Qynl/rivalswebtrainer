export const GLOVES = Object.freeze(
  Object.fromEntries(
    definitions.map(
      ([
        key,
        name,
        cost,
        ability,
        activation,
        description,
        color,
        damage,
        power,
        range,
        interval,
        windup,
        ragdoll,
        abilityCooldown,
      ]) => {
        const id = `glove_${key}`;
        return [
          id,
          Object.freeze({
            id,
            key,
            name,
            cost,
            ability,
            activation,
            description,
            color,
            damage,
            power,
            range,
            interval,
            windup,
            ragdoll,
            abilityCooldown,
            glove: true,
            slot: 0,
            type: "melee",
            mag: Infinity,
            reserve: Infinity,
            reload: 0,
            speed: 1,
            recoil: 0,
            spread: 0,
            auto: true,
          }),
        ];
      },
    ),
  ),
);
export const DEFAULT_GLOVE = "glove_default";
// Internal compatibility slots are never equippable in glove matches.
export const gloveLoadout = (id = DEFAULT_GLOVE) => [
  GLOVES[id] ? id : DEFAULT_GLOVE,
  "pistol",
  "fists",
  "grenade",
];
export const isGlove = (id) => Object.hasOwn(GLOVES, id);
export const canUseGlove = (id, slaps) =>
  isGlove(id) && Number.isSafeInteger(slaps) && slaps >= GLOVES[id].cost;
export const sanitizeSlaps = (value) =>
  Number.isSafeInteger(value) && value >= 0 ? Math.min(10_000_000, value) : 0;

// Display ordering is separate from the append-only wire-ID ordering.
export const GLOVE_ROSTER = Object.freeze(
  Object.values(GLOVES).sort((a, b) => a.cost - b.cost),
);
export const gloveCategory = (g) =>
  ["dual", "dice", "boomerang", "bull", "extended"].includes(g.key)
    ? "Power"
    : ["ghost", "diamond", "golden", "reverse"].includes(g.key)
      ? "Defense"
      : [
            "default",
            "acrobat",
            "flash",
            "spring",
            "space",
            "magnet",
            "speedrun",
            "thanos",
            "swapper",
          ].includes(g.key)
        ? "Mobility"
        : "Control";
